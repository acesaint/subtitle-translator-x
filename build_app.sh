#!/bin/bash
# =====================================================================
#  build_app.sh — (re)generate the *thin* "Subtitle Translator.app"
#
#  Usually you don't run this directly: `./setup.sh` calls it after the
#  virtual environment is ready. Run it on its own whenever the icon or
#  Info.plist should be refreshed:
#
#      ./build_app.sh
#
#  This bundle contains no Python: it is a small shell launcher that runs
#  `main.py` with this folder's .venv. Handy while developing (code edits
#  take effect immediately, no rebuild). For an app that runs on a Mac
#  *without* Python, use ./build_release.sh instead.
#
#  The launcher is relocatable: it looks for main.py next to the .app, so
#  copying the whole project folder to another Mac and running ./setup.sh
#  there is enough — nothing is hard-wired at build time.
# =====================================================================
set -euo pipefail

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP_NAME="Subtitle Translator"
APP_DIR="$PROJECT_DIR/$APP_NAME.app"
BUNDLE_ID="com.workbuddy.subtitle-translator"

echo "==> Building $APP_NAME.app from $PROJECT_DIR"

# --- sanity checks ---------------------------------------------------------
[ -x "$PROJECT_DIR/.venv/bin/python" ] || {
    echo "ERROR: .venv not found. Run ./setup.sh first — it creates the" >&2
    echo "       virtual environment and then calls this script." >&2
    exit 1
}

# --- clean previous bundle -------------------------------------------------
rm -rf "$APP_DIR"
mkdir -p "$APP_DIR/Contents/MacOS" "$APP_DIR/Contents/Resources"

# --- icon (optional) -------------------------------------------------------
# A machine without ffmpeg simply gets the generic macOS icon.
if [ -x "$PROJECT_DIR/tools/make_icon.sh" ] \
   && "$PROJECT_DIR/tools/make_icon.sh" "$APP_DIR/Contents/Resources/icon.icns"; then
    echo "    icon   -> Contents/Resources/icon.icns"
else
    echo "    icon   -> skipped (needs ffmpeg); generic icon will be used."
fi

# --- launcher --------------------------------------------------------------
cat > "$APP_DIR/Contents/MacOS/launcher" <<LAUNCHER
#!/bin/bash
# Subtitle Translator — double-click launcher (generated by build_app.sh)
#
# Finder launches apps with a minimal PATH, so Homebrew's ffmpeg would be
# missing; we prepend the usual locations. Everything is logged to
# ~/Library/Logs/SubtitleTranslator.log because stdout/stderr go nowhere
# when the app is double-clicked.

LOG_FILE="\$HOME/Library/Logs/SubtitleTranslator.log"
STATE_FILE="\$HOME/Library/Application Support/SubtitleTranslator/project_path"
BUILD_TIME_PROJECT="$PROJECT_DIR"

export PATH="/opt/homebrew/bin:/usr/local/bin:\$PATH"

# --- locate the project folder ---------------------------------------------
# The .app holds no code, so it must find main.py. Three candidates, in order:
#   1. the folder next to this bundle   (a copied project folder just works)
#   2. the folder remembered from the last launch  (lets you drag the app to
#      /Applications afterwards and keep it working)
#   3. the folder this bundle was built from  (same-machine rebuilds)
find_project() {
    local self_dir bundle_dir sibling remembered
    self_dir="\$(cd "\$(dirname "\$0")" && pwd)" || return 1
    bundle_dir="\$(cd "\$self_dir/../.." && pwd)" || return 1
    sibling="\$(cd "\$bundle_dir/.." && pwd)" || return 1

    if [ -f "\$sibling/main.py" ]; then echo "\$sibling"; return 0; fi

    if [ -f "\$STATE_FILE" ]; then
        remembered="\$(cat "\$STATE_FILE" 2>/dev/null)"
        if [ -n "\$remembered" ] && [ -f "\$remembered/main.py" ]; then
            echo "\$remembered"; return 0
        fi
    fi

    if [ -f "\$BUILD_TIME_PROJECT/main.py" ]; then echo "\$BUILD_TIME_PROJECT"; return 0; fi
    return 1
}

PROJECT_DIR="\$(find_project || true)"

mkdir -p "\$(dirname "\$LOG_FILE")" 2>/dev/null
{
    echo "============================================================"
    echo "  \$(date '+%Y-%m-%d %H:%M:%S')  launching Subtitle Translator"
    echo "  project   : \${PROJECT_DIR:-<not found>}"
    echo "  PATH      : \$PATH"
    echo "  ffmpeg    : \$(command -v ffmpeg 2>/dev/null || echo 'NOT FOUND')"
    echo "  python    : \$PROJECT_DIR/.venv/bin/python"
    echo "============================================================"
} >> "\$LOG_FILE" 2>&1

if [ -z "\$PROJECT_DIR" ]; then
    osascript -e "display dialog \"The Subtitle Translator project folder could not be found.\n\nThis app contains no code of its own — it needs the folder holding main.py.\n\nFix: keep the app next to the project folder, or copy the whole\nsubtitle-translator folder over and run ./setup.sh inside it.\" with title \"Subtitle Translator\" buttons {\"OK\"} default button \"OK\" with icon stop" >/dev/null 2>&1
    exit 1
fi

# Remember where the project lives, so a later move of the .app still works.
mkdir -p "\$(dirname "\$STATE_FILE")" 2>/dev/null
printf '%s' "\$PROJECT_DIR" > "\$STATE_FILE" 2>/dev/null

VENV_PY="\$PROJECT_DIR/.venv/bin/python"
if [ ! -x "\$VENV_PY" ]; then
    osascript -e "display dialog \"The Python environment is missing.\n\nOpen Terminal in:\n\$PROJECT_DIR\n\nand run:\n  ./setup.sh\" with title \"Subtitle Translator\" buttons {\"OK\"} default button \"OK\" with icon stop" >/dev/null 2>&1
    exit 1
fi

# A .venv copied from another Mac points at that machine's interpreter and
# will not run here; catch it with a clear message instead of a broken app.
if ! "\$VENV_PY" -c "import sys" >/dev/null 2>&1; then
    osascript -e "display dialog \"This Python environment was created on another Mac and cannot run here.\n\nOpen Terminal in:\n\$PROJECT_DIR\n\nand run:\n  ./setup.sh\" with title \"Subtitle Translator\" buttons {\"OK\"} default button \"OK\" with icon stop" >/dev/null 2>&1
    exit 1
fi

if ! command -v ffmpeg >/dev/null 2>&1; then
    osascript -e "display dialog \"ffmpeg was not found.\n\nThe app cannot extract embedded subtitles without it.\n\nInstall it with:  brew install ffmpeg\" with title \"Subtitle Translator\" buttons {\"OK\"} default button \"OK\" with icon caution" >/dev/null 2>&1
    echo "[launcher] WARNING: ffmpeg not in PATH" >> "\$LOG_FILE"
fi

cd "\$PROJECT_DIR" || exit 1
export PYTHONPATH="\$PROJECT_DIR"

"\$VENV_PY" main.py >> "\$LOG_FILE" 2>&1
STATUS=\$?

if [ "\$STATUS" -ne 0 ]; then
    echo "[launcher] python exited with status \$STATUS at \$(date '+%H:%M:%S')" >> "\$LOG_FILE"
    osascript -e "display dialog \"Subtitle Translator closed unexpectedly (exit code \$STATUS).\n\nThe full log is at:\n\$LOG_FILE\" with title \"Subtitle Translator\" buttons {\"OK\"} default button \"OK\" with icon stop" >/dev/null 2>&1
fi
exit "\$STATUS"
LAUNCHER
chmod +x "$APP_DIR/Contents/MacOS/launcher"
echo "    launcher -> Contents/MacOS/launcher (executable)"

# --- Info.plist ------------------------------------------------------------
cat > "$APP_DIR/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDevelopmentRegion</key>
	<string>English</string>
	<key>CFBundleDisplayName</key>
	<string>Subtitle Translator</string>
	<key>CFBundleExecutable</key>
	<string>launcher</string>
	<key>CFBundleIconFile</key>
	<string>icon.icns</string>
	<key>CFBundleIdentifier</key>
	<string>$BUNDLE_ID</string>
	<key>CFBundleInfoDictionaryVersion</key>
	<string>6.0</string>
	<key>CFBundleName</key>
	<string>Subtitle Translator</string>
	<key>CFBundlePackageType</key>
	<string>APPL</string>
	<key>CFBundleShortVersionString</key>
	<string>1.1</string>
	<key>CFBundleVersion</key>
	<string>2</string>
	<key>LSMinimumSystemVersion</key>
	<string>10.15</string>
	<key>LSApplicationCategoryType</key>
	<string>public.app-category.video</string>
	<key>NSHighResolutionCapable</key>
	<true/>
	<key>NSPrincipalClass</key>
	<string>NSApplication</string>
	<key>NSSupportsAutomaticGraphicsSwitching</key>
	<true/>
</dict>
</plist>
PLIST
echo "    plist   -> Contents/Info.plist"

# --- done ------------------------------------------------------------------
echo ""
echo "==> Built: $APP_DIR"
echo "    Double-click it in Finder, or drag it to /Applications / the Dock."
echo "    Log file: ~/Library/Logs/SubtitleTranslator.log"
